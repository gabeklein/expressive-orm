describe("date", () => {
  describe("schema", () => {
    it("will create basic time columns", async () => {
      class TimeRecords extends Type {
        created = date();
        updated = date({ nullable: true });
        birthDate = date({ type: "date" });
        startTime = date({ type: "time" });
      }

      const { schema } = SchemaConnection.new([ TimeRecords ]);

      expect(String(schema)).toMatchInlineSnapshot(`
        "CREATE TABLE
          "time_records" (
            "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "created" TIMESTAMP NOT NULL,
            "updated" TIMESTAMP,
            "birth_date" DATE NOT NULL,
            "start_time" TIME NOT NULL
          );"
      `);
    });

    it("will create time columns with precision and timezone", async () => {
      class EventLog extends Type {
        timestamp = date({
          type: "timestamp",
          precision: 6,
          timezone: true
        });
        localTime = date({
          type: "time",
          precision: 3
        });
        utcTime = date({
          type: "time",
          precision: 3,
          timezone: true
        });
      }

      const { schema } = SchemaConnection.new([ EventLog ]);

      expect(String(schema)).toMatchInlineSnapshot(`
        "CREATE TABLE
          "event_log" (
            "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "timestamp" TIMESTAMPTZ (6) NOT NULL,
            "local_time" TIME(3) NOT NULL,
            "utc_time" TIMETZ (3) NOT NULL
          );"
      `);
    });
  });

  describe("serialization", () => {
    it("will store a timestamp without timezone in UTC, to the millisecond", () => {
      const field = codec(() => date());

      expect(field.encode(new Date("2023-01-15T14:30:45.123Z"))).toBe("2023-01-15 14:30:45.123");
      expect(field.decode("2023-01-15 14:30:45")).toEqual(new Date("2023-01-15T14:30:45Z"));
      expect(field.decode("2023-01-15T14:30:45.5")).toEqual(new Date("2023-01-15T14:30:45.500Z"));
    });

    it("will read a timestamp the driver parsed as local time", () => {
      const field = codec(() => date());
      const local = new Date(2023, 0, 15, 14, 30, 45);

      expect(field.decode(local)).toEqual(new Date("2023-01-15T14:30:45Z"));
    });

    it("will store a timestamp with timezone as ISO", () => {
      const field = codec(() => date({ type: "timestamp", timezone: true }));
      const value = new Date("2023-01-15T14:30:45.123Z");

      expect(field.encode(value)).toBe("2023-01-15T14:30:45.123Z");
      expect(field.decode(value)).toEqual(value);
    });

    it("will handle date type correctly", () => {
      const field = codec(() => date({ type: "date" }));

      expect(field.encode(new Date(2023, 0, 15, 14, 30))).toBe("2023-01-15");
      expect(field.decode("2023-01-15")).toBe("2023-01-15");
      expect(field.decode(new Date(2023, 0, 15))).toBe("2023-01-15");
    });

    it("will handle time type correctly", () => {
      const field = codec(() => date({ type: "time" }));

      expect(field.encode(new Date("2023-01-15T14:30:45.123Z"))).toBe("14:30:45");
      expect(field.decode("14:30:45")).toEqual(new Date("1970-01-01T14:30:45Z"));
    });

    it("will read time with timezone", () => {
      const field = codec(() => date({ type: "time", timezone: true }));

      expect(field.decode("14:30:45+00")).toEqual(new Date("1970-01-01T14:30:45Z"));
      expect(field.decode("14:30:45.5+05:30")).toEqual(new Date("1970-01-01T09:00:45.5Z"));
    });
  });
});

describe("portability", () => {
  it("will render the shared vocabulary", async () => {
    class Shared extends Type {
      key = str({ type: "uuid" });
      handle = str({ type: "varchar", length: 3 });
      double = num({ type: "double" });
      decimal = num({ type: "decimal", precision: 8, scale: 2 });
      flag = bool();
      data = json();
      stamp = date();
    }

    const { schema } = SchemaConnection.new([ Shared ]);

    expect(String(schema)).toMatchInlineSnapshot(`
      "CREATE TABLE
        "shared" (
          "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "key" UUID NOT NULL,
          "handle" VARCHAR(3) NOT NULL,
          "double" DOUBLE PRECISION NOT NULL,
          "decimal" DECIMAL(8, 2) NOT NULL,
          "flag" BOOLEAN NOT NULL,
          "data" TEXT NOT NULL,
          "stamp" TIMESTAMP NOT NULL
        );"
    `);
  });

  it("will refuse a datatype it can't store", () => {
    class Shared extends Type {
      stamp = date({ type: "interval" as "time" });
    }

    expect(() => SchemaConnection.new([ Shared ])).toThrow("SchemaConnection can't store date type 'interval' (Shared.stamp).");
  });

  it("will reject a timezone without time", () => {
    // @ts-expect-error
    column(() => date({ type: "date", timezone: true }));
  });

  it("will reject storage-only options", () => {
    // @ts-expect-error
    column(() => bool({ type: "varchar", either: ["YES", "NO"] }));
    // @ts-expect-error
    column(() => num({ type: "serial" }));
  });
});
